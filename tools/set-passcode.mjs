#!/usr/bin/env node
/* Set the dashboard passcode.
 *
 *   node tools/set-passcode.mjs "some passphrase"
 *
 * Rewrites the generated block in js/auth.js with a fresh random salt and the
 * PBKDF2-SHA256 verifier for the passphrase. The passphrase itself is never
 * written anywhere — losing it means running this again with a new one.
 *
 * Everyone already unlocked keeps a cookie holding the old verifier, so
 * changing the passcode logs every device out. That is the intent.
 */
import { randomBytes, pbkdf2Sync } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ITERATIONS = 250000;
const AUTH_FILE = join(dirname(fileURLToPath(import.meta.url)), '..', 'js', 'auth.js');

const passphrase = process.argv.slice(2).join(' ').trim();
if (!passphrase) {
    console.error('Usage: node tools/set-passcode.mjs "your passphrase"');
    process.exit(1);
}
if (passphrase.length < 6) {
    console.error('Use at least 6 characters.');
    process.exit(1);
}

const salt = randomBytes(16);
const verifier = pbkdf2Sync(passphrase, salt, ITERATIONS, 32, 'sha256');

const block = [
    "    // --- generated by tools/set-passcode.mjs — do not hand-edit ---",
    `    const SALT_B64 = '${salt.toString('base64')}';`,
    `    const VERIFY_B64 = '${verifier.toString('base64')}';`,
    `    const ITERATIONS = ${ITERATIONS};`,
    '    // --- end generated ---',
].join('\n');

const source = readFileSync(AUTH_FILE, 'utf8');
const pattern = /^ {4}\/\/ --- generated by tools\/set-passcode\.mjs.*?^ {4}\/\/ --- end generated ---$/ms;
if (!pattern.test(source)) {
    console.error(`Could not find the generated block in ${AUTH_FILE}.`);
    process.exit(1);
}

writeFileSync(AUTH_FILE, source.replace(pattern, block));
console.log(`Passcode updated in ${AUTH_FILE}.`);
console.log('Commit and push, then unlock again on each device.');
